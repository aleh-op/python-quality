#!/usr/bin/env bash
# lib.sh — the checks the Python toolchain does not already do, defined once.
#
# Each check writes neutral records to stdout, one per line:
#
#     rule<TAB>level<TAB>path<TAB>line<TAB>message[<TAB>key]
#
# `key` is optional: it disambiguates a fingerprint (`rule:path:line`) where
# one location can hold more than one finding of the same rule.
#
# gate.sh renders them for humans, findings.sh renders them as JSONL. Nothing
# in here knows about either format. Define a check once, render it twice.
#
# Sourced, never executed directly. bash 3.2 is the floor (macOS /bin/bash):
# no mapfile, no associative arrays.

# This checkout's root, so a check can reach the canonical config it compares
# against.
PQ_DIR="${PQ_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

# ── uvr / pq_py ──────────────────────────────────────────────────────────────
# uvr runs a tool from the consumer's own environment at the version uv.lock
# pins. `--locked`: a stale lock is an error, never a silent re-lock.
# `--offline`: a gate must not reach the network to find its own tools. Without
# both, `uv run` re-resolves and can fetch a DIFFERENT ruff mid-gate. `--quiet`
# keeps uv's "Building ..." chatter out of the report.
uvr() { uv run --locked --offline --quiet "$@"; }

# pq_py runs OUR parsing code (TOML, JSON). Never a bare `python3`: on macOS
# that is 3.9 with no tomllib (rust-quality's lesson). uv finds a >=3.11
# interpreter — the project's own venv first — and never downloads one offline.
pq_py() { uv run --no-project --offline --quiet --python '>=3.11' python -I "$@"; }

# ── ai_lint <file...> ────────────────────────────────────────────────────────
# Residue a linter cannot see. Checked against ruff 0.17.1 with ruff.base.toml
# (ERA001 included) before being written: a file containing all three produces
# ZERO ruff diagnostics, so none of this double-reports.
#
# Every rule pipeline ends in `|| true`, and that is load-bearing: grep exits 1
# when a rule does not match, which is the normal case. Callers run this under
# `set -euo pipefail` inside a process substitution, so an unguarded non-match
# would kill the subshell and silently skip every later rule and file.
ai_lint() {
  local f
  for f in "$@"; do
    case "$f" in
      .venv/*|*/.venv/*|build/*|*/build/*|dist/*|*/dist/*) continue ;;
      *_pb2.py|*_pb2_grpc.py|*/migrations/*) continue ;;
    esac
    [ -f "$f" ] || continue
    head -5 "$f" 2>/dev/null | grep -qE '^# *(@generated|Code generated|Generated by)' && continue

    grep -nHE '(TODO|FIXME|XXX)\((claude|ai|bot|gpt|assistant|copilot|codex)\b' "$f" 2>/dev/null \
      | _rec agent-todo error 'agent-tagged TODO — give it a real owner or open an issue' || true
    grep -nHE '#.*\b([Aa]s requested|[Pp]er your request|[Aa]s you (asked|requested|wanted)|[Ii]n response to your request)\b' "$f" 2>/dev/null \
      | _rec ai-self-ref error 'prompt artifact — the comment is talking to the agent' || true
    grep -nHE '#[[:space:]]*(REMOVED|PREVIOUSLY|WAS):[[:space:]]' "$f" 2>/dev/null \
      | _rec diff-relic error 'diff relic — belongs in commit history, not source' || true
  done
}

# _rec <rule> <level> <message>  — turn `path:line:text` on stdin into records.
_rec() {
  local rule="$1" level="$2" msg="$3" line path lineno
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    path="${line%%:*}"; lineno="${line#*:}"; lineno="${lineno%%:*}"
    printf '%s\t%s\t%s\t%s\t%s\n' "$rule" "$level" "$path" "$lineno" "$msg"
  done
}

# ── god_files ────────────────────────────────────────────────────────────────
# The one structural cap ruff has no opinion about. Complexity is NOT here:
# C901 and PLR09xx in ruff.base.toml own that.
#
# Counts CODE lines — neither blank nor `#` comment (rust-quality's lesson: a
# cap measured with `wc -l` partly measures prose). Docstrings count; ruff
# cannot tell a docstring from code without parsing and neither can awk.
#
# `-c core.quotePath=` keeps a non-ASCII path as its own bytes. `--deduplicate`:
# a conflicted path is listed once per merge stage, and a gate run mid-merge
# reported every file three times (rust-quality, found by running it).
god_files() {
  local cap="${CAP_LOC:-500}"
  # shellcheck disable=SC2016  # an awk program handed to xargs, not a shell expansion
  git -c core.quotePath= ls-files --deduplicate -- '*.py' 2>/dev/null \
    | grep -vE '(^|/)(\.venv|build|dist|migrations|tests)/|(^|/)test_[^/]*\.py$|_pb2(_grpc)?\.py$' \
    | tr '\n' '\0' | xargs -0 awk -v cap="$cap" '
        function emit() {
          if (file != "" && n > cap)
            printf "god-file\twarning\t%s\t1\t%d code lines over the %d cap\n", file, n, cap
        }
        FNR == 1 { if (NR > 1) emit(); file = FILENAME; n = 0 }
        {
          line = $0; sub(/^[ \t]+/, "", line)
          if (line != "" && line !~ /^#/) n++
        }
        END { emit() }' 2>/dev/null \
    || true
}

# ── staged_py / tracked_py ───────────────────────────────────────────────────
# `--relative` is load-bearing (ts-quality's real bug): `git diff --cached`
# prints REPO-ROOT-relative paths while `git ls-files` prints CWD-relative
# ones. In a repo gated with `dir: api`, staged paths came back as `api/x.py`
# while the gate stood in `api/`, every `[ -f ]` failed, and ai-lint reported
# "clean" having read nothing.
staged_py()  { git -c core.quotePath= diff --cached --relative --name-only --diff-filter=ACMR -- '*.py' '*.pyi' 2>/dev/null; }
tracked_py() { git -c core.quotePath= ls-files --deduplicate -- '*.py' '*.pyi' 2>/dev/null; }
